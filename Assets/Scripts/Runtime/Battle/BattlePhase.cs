namespace BlackHeart
{
    public enum BattlePhase
    {
        None,
        Intro,        // враг появился и замахивается — бить нельзя
        ToDefense,    // враг атакует, улетает вверх, рамка расширяется
        Defense,      // летят пули — их нужно рубить
        ToAttack,     // рамка сужается, враг возвращается
        Attack,       // несколько секунд, чтобы рубануть врага
        Laugh,        // игрок не попал — враг смеётся
        Victory       // враг повержен
    }
}
